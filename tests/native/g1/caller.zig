// Zig 0.13 caller for the G1 sample calc: reads "i0 i1" lines, prints "i0 i1 status result" per line.
const std = @import("std");
const om = @import("omega_native.zig"); // generated by tools/native, nothing typed by hand

pub fn main() !void {
    const in = std.io.getStdIn().reader();
    const out = std.io.getStdOut().writer();
    var buf: [128]u8 = undefined;
    while (try in.readUntilDelimiterOrEof(&buf, '\n')) |line| {
        var it = std.mem.tokenizeScalar(u8, line, ' ');
        const a = try std.fmt.parseInt(u64, it.next().?, 10);
        const b = try std.fmt.parseInt(u64, it.next().?, 10);
        var r: u64 = 0;
        const s = om.omega_calc(&r, a, b);
        try out.print("{d} {d} {d} {d}\n", .{ a, b, s, r });
    }
}
