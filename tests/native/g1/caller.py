# Python caller for the G1 sample calc: reads "i0 i1" lines, prints "i0 i1 status result" per line.
import ctypes, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # python3 -I drops this folder
import omega_native as om  # generated by tools/native, nothing typed by hand
for line in sys.stdin:
    a, b = map(int, line.split())
    r = ctypes.c_uint64(0)
    s = om.omega_calc(ctypes.byref(r), a, b)
    print(a, b, s, r.value)
