// Rust caller for the G1 sample calc: reads "i0 i1" lines, prints "i0 i1 status result" per line.
mod omega_native; // generated by tools/native, nothing typed by hand
use std::io::BufRead;

fn main() {
    for line in std::io::stdin().lock().lines() {
        let line = line.expect("stdin");
        let mut it = line.split_whitespace().map(|t| t.parse::<u64>().expect("u64"));
        let (a, b) = (it.next().expect("i0"), it.next().expect("i1"));
        let mut r: u64 = 0;
        let s = unsafe { omega_native::omega_calc(&mut r, a, b) };
        println!("{} {} {} {}", a, b, s, r);
    }
}
