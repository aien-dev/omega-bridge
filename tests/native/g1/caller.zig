// Zig caller for the G1 sample calc: reads "i0 i1" lines, prints "i0 i1 status result" per line.
// Stdin and stdout go through the C library (std.c.read, std.c.write), which Zig 0.13 and 0.17 share;
// std.io changed between them.
const std = @import("std");
const om = @import("omega_native.zig"); // generated by tools/native, nothing typed by hand

fn put(s: []const u8) void {
    var off: usize = 0;
    while (off < s.len) {
        const n = std.c.write(1, s[off..].ptr, s.len - off);
        if (n <= 0) std.c.exit(3);
        off += @intCast(n);
    }
}

pub fn main() void {
    var in: [1 << 16]u8 = undefined;
    var len: usize = 0;
    while (len < in.len) {
        const n = std.c.read(0, in[len..].ptr, in.len - len);
        if (n < 0) std.c.exit(2);
        if (n == 0) break;
        len += @intCast(n);
    }
    if (len == in.len) std.c.exit(2);
    var lines = std.mem.tokenizeScalar(u8, in[0..len], '\n');
    while (lines.next()) |line| {
        var it = std.mem.tokenizeScalar(u8, line, ' ');
        const a = std.fmt.parseInt(u64, it.next() orelse std.c.exit(2), 10) catch std.c.exit(2);
        const b = std.fmt.parseInt(u64, it.next() orelse std.c.exit(2), 10) catch std.c.exit(2);
        var r: u64 = 0;
        const s = om.omega_calc(&r, a, b);
        var out: [96]u8 = undefined;
        put(std.fmt.bufPrint(&out, "{d} {d} {d} {d}\n", .{ a, b, s, r }) catch std.c.exit(3));
    }
}
