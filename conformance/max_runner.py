"""MAX-side conformance runner for the frozen matmul and causal GQA contracts.

Reads one fixture generated by conformance/oracle.py, builds a MAX graph, runs
it in a separate process, and writes raw f32 output plus run metadata. The
oracle is deliberately not called here: conformance/verify.py is the independent
judge. A CPU run validates the harness only; a GPU run is device evidence and
must carry the Spark window identifier.

  max_runner.py --fixture F.json --device cpu|gpu --out PREFIX
"""
import argparse
import json
import math
import os
import struct
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import oracle  # noqa: E402

import numpy as np  # noqa: E402
from max.driver import Accelerator, CPU, Buffer  # noqa: E402
from max.dtype import DType  # noqa: E402
from max.engine import InferenceSession  # noqa: E402
from max.graph import DeviceRef, Graph, TensorType, ops  # noqa: E402


def f32_from_hex(items):
    return np.array([oracle.f32_from_bits(int(x, 16)) for x in items], dtype=np.float32)


def bf16_from_hex(items):
    return np.array([oracle.bf16_from_bits(int(x, 16)) for x in items], dtype=np.float32)


def matmul_graph(m, k, n, dev):
    dt = DeviceRef.from_device(dev)
    return Graph(
        "omega-matmul-bf16-v1",
        input_types=[
            TensorType(DType.float32, [m, k], device=dt),
            TensorType(DType.float32, [k, n], device=dt),
        ],
        # Operands are exact bf16 values carried in f32. This is the contract's
        # fp32-accumulation path; MAX's bf16 output dtype would round the result
        # before the contract's f32 comparison. Recorded in metadata.
        forward=lambda a, b: ops.matmul(a, b),
    )


def attention_graph(r, t, hq, hkv, hd, base, dev):
    group = hq // hkv
    dt = DeviceRef.from_device(dev)
    def forward(q, k, v, mask):
        scale = ops.constant(1.0 / math.sqrt(hd), DType.float32, device=dt)
        kk = ops.repeat_interleave(k, group, axis=1)          # [T, Hq, D]
        vv = ops.transpose(ops.repeat_interleave(v, group, axis=1), 0, 1)  # [Hq, T, D]
        kt = ops.transpose(ops.transpose(kk, 0, 1), 1, 2)     # [Hq, D, T]
        qt = ops.transpose(q, 0, 1)                           # [Hq, R, D]
        scores = ops.mul(ops.matmul(qt, kt), scale)           # [Hq, R, T]
        m = ops.broadcast_to(ops.reshape(mask, [1, r, t]), scores.shape)
        probs = ops.softmax(ops.add(scores, m), -1)
        return ops.transpose(ops.matmul(probs, vv), 0, 1)     # [R, Hq, D]

    return Graph(
        "omega-gqa-causal-v1",
        input_types=[
            TensorType(DType.float32, [r, hq, hd], device=dt),
            TensorType(DType.float32, [t, hkv, hd], device=dt),
            TensorType(DType.float32, [t, hkv, hd], device=dt),
            TensorType(DType.float32, [r, t], device=dt),
        ],
        forward=forward,
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixture", required=True)
    ap.add_argument("--device", choices=["cpu", "gpu"], default="cpu")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    f = json.load(open(args.fixture))
    if args.device == "gpu":
        # Refuse before constructing Accelerator: construction itself opens the
        # reserved chip (REVIEW B-01).
        if os.environ.get("SPARK_WINDOW") is None:
            print("gpu run refused: SPARK_WINDOW is not set (no authorized window)", file=sys.stderr)
            return 3
        dev = Accelerator()
    else:
        dev = CPU()
    session = InferenceSession(devices=[dev])
    t0 = time.perf_counter()

    if f["name"] == "matmul-v1":
        m, k, n = (f["shape"][x] for x in ("m", "k", "n"))
        a = bf16_from_hex(f["inputs"]["a"]).reshape(m, k)
        b = bf16_from_hex(f["inputs"]["b"]).reshape(k, n)
        model = session.load(matmul_graph(m, k, n, dev))
        t_compile = time.perf_counter() - t0
        t1 = time.perf_counter()
        out = model.execute(Buffer.from_numpy(a), Buffer.from_numpy(b))[0].to_numpy()
        t_run = time.perf_counter() - t1
        flat = out.astype(np.float32).ravel()
        shape = [m, n]
    elif f["name"] == "gqa-causal-v1":
        s = f["shape"]
        r, base, t, hq, hkv, hd = s["r"], s["base"], s["t"], s["hq"], s["hkv"], s["head_dim"]
        q = f32_from_hex(f["inputs"]["q"]).reshape(r, hq, hd)
        kk = f32_from_hex(f["inputs"]["k"]).reshape(t, hkv, hd)
        vv = f32_from_hex(f["inputs"]["v"]).reshape(t, hkv, hd)
        mask = np.full((r, t), -np.inf, dtype=np.float32)
        for i in range(r):
            for j in range(t):
                if j <= base + i:
                    mask[i, j] = 0.0
        model = session.load(attention_graph(r, t, hq, hkv, hd, base, dev))
        t_compile = time.perf_counter() - t0
        t1 = time.perf_counter()
        out = model.execute(*[Buffer.from_numpy(x) for x in (q, kk, vv, mask)])[0].to_numpy()
        t_run = time.perf_counter() - t1
        flat = out.astype(np.float32).ravel()
        shape = [r, hq, hd]
    else:
        print(f"unknown fixture {f['name']}", file=sys.stderr)
        return 2

    with open(args.out + ".bin", "wb") as fp:
        fp.write(struct.pack("<%df" % flat.size, *[float(x) for x in flat]))
    meta = {
        "runner": "modular-max",
        "device": args.device,
        "shape": shape,
        "contract_id": f["contract_id"],
        "max_version": _max_version(),
        "accelerator_api": _api() if args.device == "gpu" else "cpu",
        "compile_seconds": t_compile,
        "execute_seconds": t_run,
        "spark_window": os.environ.get("SPARK_WINDOW"),
        "numeric_path": "fp32-mul-add (exact for this fixture)" if f["name"] == "matmul-v1" else "fp32-softmax",
        "output_sha256": _sha(args.out + ".bin"),
    }
    with open(args.out + ".json", "w") as fp:
        json.dump(meta, fp, indent=2, sort_keys=True)
        fp.write("\n")
    print(json.dumps(meta, sort_keys=True))
    return 0


def _max_version():
    try:
        import max as m
        version = getattr(m, "__version__", None)
        # The requested release is not evidence of the installed release.
        return version if isinstance(version, str) and version.strip() else "unknown"
    except Exception:
        return "unknown"


def _api():
    try:
        from max.driver import accelerator_api
        return accelerator_api()
    except Exception:
        return "unknown"


def _sha(path):
    import hashlib
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


if __name__ == "__main__":
    sys.exit(main())
