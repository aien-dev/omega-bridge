// Rust caller for the omega-bridge native call ABI v1 test library (no crates).
mod omega_native; // every Omega declaration: generated by tools/native, nothing typed by hand
use omega_native::*;

fn main() {
    const SENTINEL: u64 = 6148914691236517205;
    let mut fails = 0;
    let mut check = |name: &str, ok: bool| {
        println!("{} {}", if ok { "PASS" } else { "FAIL" }, name);
        if !ok {
            fails += 1;
        }
    };
    let mut r: u64 = 0;
    unsafe {
        check("madd 3*5+7 = 22", omega_madd(&mut r, 3, 5, 7) == 0 && r == 22);
        check("madd wraps = 3", omega_madd(&mut r, u64::MAX, 2, 5) == 0 && r == 3);
        check("madd large", omega_madd(&mut r, 1311768467463790320, 18364758544493064720, 1085102592571150095) == 0
            && r == 3637949782307626511);
        check("madd signed bits = -13", omega_madd(&mut r, (-3i64) as u64, 5, 2) == 0 && r as i64 == -13);
        r = SENTINEL;
        check("smadd overflow traps 1, result unchanged", omega_smadd(&mut r, 1u64 << 62, 4, 0) == 1 && r == SENTINEL);
        let mut buf = [0u64; 4];
        check("fill k=1 traps 3, result unchanged", omega_fill(&mut r, buf.as_mut_ptr(), 4, 1) == 3 && r == SENTINEL);
        check("writes before the trap stay visible", buf == [11, 22, 0, 0]);
        check("fill k=0 = 3", omega_fill(&mut r, buf.as_mut_ptr(), 4, 0) == 0 && r == 3 && buf == [11, 22, 33, 0]);
        check("null result refused 32", omega_madd(std::ptr::null_mut(), 3, 5, 7) == 32);
        // mix: six parameters (ulong, long, view uchar 3, edit uchar 2, view ulong 2, ulong), no result.
        // 5 + 20 + 7 = 32 (calc:08302bc4); 5 + 20 + 300 is 70 over 255 (calc:a6a8bb76), so the conversion traps 5.
        let cb = [1u8, 2, 3];
        let mut db = [0u8; 2];
        let eb = [10u64, 20];
        r = SENTINEL;
        check("mix six parameters, void result writes 0",
            omega_mix(&mut r, 5, 1, cb.as_ptr(), 3, db.as_mut_ptr(), 2, eb.as_ptr(), 2, 7) == 0 && r == 0 && db == [3, 32]);
        db = [0, 0];
        r = SENTINEL;
        check("mix negative long traps 9 after both writes, result unchanged",
            omega_mix(&mut r, 5, (-1i64) as u64, cb.as_ptr(), 3, db.as_mut_ptr(), 2, eb.as_ptr(), 2, 7) == 9
                && r == SENTINEL && db == [3, 32]);
        db = [0, 0];
        check("mix uchar conversion 325 traps 5, first write visible",
            omega_mix(&mut r, 5, 1, cb.as_ptr(), 3, db.as_mut_ptr(), 2, eb.as_ptr(), 2, 300) == 5 && r == SENTINEL && db == [3, 0]);
    }
    // A std::thread has a 2 MiB stack by default; the 4,000,000-byte local array runs on the binding's own stack.
    // (7 + 1) + 7 = 15 (calc:e44bce3f).
    let t = std::thread::spawn(|| {
        let mut r: u64 = 0;
        let s = unsafe { omega_big(&mut r, 7) };
        (s, r)
    });
    check("big local array on a default std::thread = 15", t.join().map_or(false, |v| v == (0, 15)));
    println!("{} {} failure(s)", if fails > 0 { "FAIL" } else { "PASS" }, fails);
    std::process::exit(if fails > 0 { 1 } else { 0 });
}
