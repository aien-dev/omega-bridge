# Python caller for the omega-bridge native call ABI v1 test library (ctypes, standard library only).
import ctypes, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # python3 -I drops this folder; the binding is beside us
import omega_native as om  # every Omega declaration: generated by tools/native, nothing typed by hand
u64 = ctypes.c_uint64
SENTINEL = 6148914691236517205
fails = 0
def check(name, ok):
    global fails
    print(("PASS " if ok else "FAIL ") + name)
    fails += not ok
def bits(v):  # signed Python int -> canonical 64-bit two's-complement bits
    return v & (2**64 - 1)
def signed(b):
    return b - 2**64 if b >= 2**63 else b
r = u64(0)
check("madd 3*5+7 = 22", om.omega_madd(ctypes.byref(r), 3, 5, 7) == 0 and r.value == 22)
check("madd wraps = 3", om.omega_madd(ctypes.byref(r), 2**64 - 1, 2, 5) == 0 and r.value == 3)
check("madd large", om.omega_madd(ctypes.byref(r), 1311768467463790320, 18364758544493064720, 1085102592571150095) == 0
      and r.value == 3637949782307626511)
check("madd signed bits = -13", om.omega_madd(ctypes.byref(r), bits(-3), 5, 2) == 0 and signed(r.value) == -13)
r = u64(SENTINEL)
check("smadd overflow traps 1, result unchanged", om.omega_smadd(ctypes.byref(r), 2**62, 4, 0) == 1 and r.value == SENTINEL)
buf = (u64 * 4)()
check("fill k=1 traps 3, result unchanged", om.omega_fill(ctypes.byref(r), buf, 4, 1) == 3 and r.value == SENTINEL)
check("writes before the trap stay visible", list(buf) == [11, 22, 0, 0])
check("fill k=0 = 3", om.omega_fill(ctypes.byref(r), buf, 4, 0) == 0 and r.value == 3 and list(buf) == [11, 22, 33, 0])
check("null result refused 32", om.omega_madd(None, 3, 5, 7) == 32)
print(("FAIL " if fails else "PASS ") + "%d failure(s)" % fails)
sys.exit(fails != 0)
